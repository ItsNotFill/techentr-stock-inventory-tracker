/**
 * Stock counts. Every function takes a transaction from `withUser`, so RLS
 * applies: anyone edits and submits their own draft; owners and managers
 * approve or reject.
 *
 *   draft -> submitted -> approved | rejected
 *
 * Submit fixes the count time (`submitted_at`) and stores a provisional
 * theoretical stock. Approval recomputes the theoretical stock as of that
 * time, snapshots the cost, and writes one count_adjust per line
 * (counted - theoretical) dated at the count time. Nothing touches the ledger
 * before approval (DECISIONS.md 8, 9).
 */

export class CountError extends Error {
  constructor(
    message: string,
    readonly field?: string,
  ) {
    super(message);
    this.name = "CountError";
  }
}

export type CountSummary = {
  id: string;
  status: CountStatus;
  countedBy: string;
  /** Known to owners and managers; null for staff. */
  countedByEmail: string | null;
  startedAt: Date;
  submittedAt: Date | null;
  approvedAt: Date | null;
  reviewNote: string | null;
  lineCount: number;
};

/** Counts of the location, newest first. */
export async function listCounts(tx: Tx, locationId: string, limit = 50): Promise<CountSummary[]> {
  const rows = await tx.execute<{
    id: string;
    status: CountStatus;
    counted_by: string;
    counted_by_email: string | null;
    started_at: string;
    submitted_at: string | null;
    approved_at: string | null;
    review_note: string | null;
    line_count: number;
  }>(sql`
    select s.id, s.status, s.counted_by, m.email as counted_by_email, s.started_at, s.submitted_at,
           s.approved_at, s.review_note,
           (select count(*)::int from public.count_lines l where l.session_id = s.id) as line_count
    from public.count_sessions s
    left join public.list_location_members(${locationId}::uuid) m on m.user_id = s.counted_by
    where s.location_id = ${locationId}::uuid
    order by coalesce(s.submitted_at, s.started_at) desc
    limit ${limit}
  `);
  const date = (value: string | null) => (value ? new Date(value) : null);
  return rows.map((row) => ({
    id: row.id,
    status: row.status,
    countedBy: row.counted_by,
    countedByEmail: row.counted_by_email,
    startedAt: new Date(row.started_at),
    submittedAt: date(row.submitted_at),
    approvedAt: date(row.approved_at),
    reviewNote: row.review_note,
    lineCount: row.line_count,
  }));
}

/**
 * Starts a count, or returns the user's draft when they already have one.
 * `clientId` is generated by the phone: calling again with the same id (a
 * retried request, later an offline sync) returns the same count.
 */
export async function startCount(tx: Tx, locationId: string, userId: string, clientId: string): Promise<string> {
  const [draft] = await tx
    .select({ id: countSessions.id })
    .from(countSessions)
    .where(
      and(
        eq(countSessions.locationId, locationId),
        eq(countSessions.countedBy, userId),
        eq(countSessions.status, "draft"),
      ),
    )
    .orderBy(desc(countSessions.startedAt))
    .limit(1);
  if (draft) return draft.id;

  const [created] = await tx
    .insert(countSessions)
    .values({ locationId, clientId, countedBy: userId, status: "draft" })
    .onConflictDoNothing({ target: countSessions.clientId })
    .returning({ id: countSessions.id });
  if (created) return created.id;

  const [existing] = await tx
    .select({ id: countSessions.id })
    .from(countSessions)
    .where(and(eq(countSessions.clientId, clientId), eq(countSessions.locationId, locationId), eq(countSessions.countedBy, userId)));
  if (!existing) throw new CountError("This count could not be started. Try again.");
  return existing.id;
}

export type CountSheetIngredient = {
  id: string;
  name: string;
  baseUnit: BaseUnit;
  storageArea: string | null;
  packSizes: { id: string; label: string; qtyInBaseUnit: string; isDefault: boolean }[];
  /** What was entered so far, in base units; null when not counted yet. */
  countedQty: string | null;
  /** Provisional (after submit) or final (after approval) theoretical stock. */
  theoreticalQty: string | null;
};

export type CountSheet = {
  id: string;
  status: CountStatus;
  countedBy: string;
  startedAt: Date;
  submittedAt: Date | null;
  approvedAt: Date | null;
  reviewNote: string | null;
  /** Active ingredients, plus archived ones that are on this count, by storage area then name. */
  ingredients: CountSheetIngredient[];
};

export async function getCountSheet(tx: Tx, locationId: string, sessionId: string): Promise<CountSheet | null> {
  const [session] = await tx
    .select()
    .from(countSessions)
    .where(and(eq(countSessions.id, sessionId), eq(countSessions.locationId, locationId)));
  if (!session) return null;

  const lines = await tx
    .select({ ingredientId: countLines.ingredientId, countedQty: countLines.countedQty, theoreticalQty: countLines.theoreticalQty })
    .from(countLines)
    .where(and(eq(countLines.sessionId, sessionId), eq(countLines.locationId, locationId)));
  const lineByIngredient = new Map(lines.map((line) => [line.ingredientId, line]));

  const rows = await tx
    .select({
      id: ingredients.id,
      name: ingredients.name,
      baseUnit: ingredients.baseUnit,
      storageArea: ingredients.storageArea,
      isActive: ingredients.isActive,
    })
    .from(ingredients)
    .where(eq(ingredients.locationId, locationId))
    .orderBy(asc(sql`coalesce(lower(${ingredients.storageArea}), '~')`), asc(sql`lower(${ingredients.name})`));
  const visible = rows.filter((row) => row.isActive || lineByIngredient.has(row.id));

  const packs = await tx
    .select()
    .from(packSizes)
    .where(eq(packSizes.locationId, locationId))
    .orderBy(asc(packSizes.qtyInBaseUnit));

  return {
    id: session.id,
    status: session.status,
    countedBy: session.countedBy,
    startedAt: session.startedAt,
    submittedAt: session.submittedAt,
    approvedAt: session.approvedAt,
    reviewNote: session.reviewNote,
    ingredients: visible.map((row) => ({
      id: row.id,
      name: row.name,
      baseUnit: row.baseUnit,
      storageArea: row.storageArea,
      packSizes: packs
        .filter((pack) => pack.ingredientId === row.id)
        .map((pack) => ({ id: pack.id, label: pack.label, qtyInBaseUnit: pack.qtyInBaseUnit, isDefault: pack.isDefault })),
      countedQty: lineByIngredient.get(row.id)?.countedQty ?? null,
      theoreticalQty: lineByIngredient.get(row.id)?.theoreticalQty ?? null,
    })),
  };
}

async function requireOwnDraft(tx: Tx, locationId: string, userId: string, sessionId: string) {
  const [session] = await tx
    .select({ status: countSessions.status, countedBy: countSessions.countedBy })
    .from(countSessions)
    .where(and(eq(countSessions.id, sessionId), eq(countSessions.locationId, locationId)))
    .for("update");
  if (!session) throw new CountError("This count no longer exists.");
  if (session.countedBy !== userId) throw new CountError("Only the person who started this count can change it.");
  if (session.status !== "draft") throw new CountError("This count was already submitted.");
}

/**
 * Saves what was typed. Each entry is converted to base units: a display unit
 * (2.5 kg) or a pack (3 x "Bag 1 kg"). An empty amount removes the ingredient
 * from the count. Errors name the entry: `entries.<index>`.
 */
export async function saveCountEntries(
  tx: Tx,
  locationId: string,
  userId: string,
  sessionId: string,
  entries: CountEntry[],
): Promise<{ saved: number; removed: number }> {
  await requireOwnDraft(tx, locationId, userId, sessionId);
  if (entries.length === 0) return { saved: 0, removed: 0 };

  const ids = [...new Set(entries.map((entry) => entry.ingredientId))];
  const known = await tx
    .select({ id: ingredients.id, baseUnit: ingredients.baseUnit })
    .from(ingredients)
    .where(and(eq(ingredients.locationId, locationId), inArray(ingredients.id, ids)));
  const ingredientById = new Map(known.map((row) => [row.id, row]));
  const packRows = await tx
    .select({ id: packSizes.id, ingredientId: packSizes.ingredientId, qtyInBaseUnit: packSizes.qtyInBaseUnit })
    .from(packSizes)
    .where(and(eq(packSizes.locationId, locationId), inArray(packSizes.ingredientId, ids)));

  const upserts: { ingredientId: string; countedQty: string }[] = [];
  const removals: string[] = [];
  entries.forEach((entry, index) => {
    const field = `entries.${index}`;
    const ingredient = ingredientById.get(entry.ingredientId);
    if (!ingredient) throw new CountError("This ingredient no longer exists.", field);
    if (entry.amount === "") {
      removals.push(entry.ingredientId);
      return;
    }
    const amount = parseQuantityInput(entry.amount);
    if (!amount) throw new CountError(`"${entry.amount}" is not a number.`, field);
    if (amount.isNegative()) throw new CountError("A count cannot be below zero.", field);
    try {
      upserts.push({ ingredientId: entry.ingredientId, countedQty: resolveEntry(ingredient, packRows, amount, entry.unit).qtyBase });
    } catch (error) {
      if (error instanceof EntryError) throw new CountError(error.message, field);
      throw error;
    }
  });

  if (removals.length > 0) {
    await tx
      .delete(countLines)
      .where(and(eq(countLines.sessionId, sessionId), eq(countLines.locationId, locationId), inArray(countLines.ingredientId, removals)));
  }
  for (const upsert of upserts) {
    await tx
      .insert(countLines)
      .values({ locationId, sessionId, ingredientId: upsert.ingredientId, countedQty: upsert.countedQty })
      .onConflictDoUpdate({
        target: [countLines.sessionId, countLines.ingredientId],
        set: { countedQty: upsert.countedQty, updatedAt: new Date() },
      });
  }
  return { saved: upserts.length, removed: removals.length };
}

/**
 * Submits the user's draft. The count time is now, or the given moment when
 * the count was finished earlier (the seed; later, a count synced from an
 * offline phone). It can never be in the future. The theoretical stock at
 * that time is stored on each line as a first figure; approval recomputes it.
 */
export async function submitCount(
  tx: Tx,
  locationId: string,
  userId: string,
  sessionId: string,
  countTime: Date = new Date(),
): Promise<Date> {
  if (Number.isNaN(countTime.getTime()) || countTime.getTime() > Date.now() + 60_000) {
    throw new CountError("The count time cannot be in the future.");
  }
  await requireOwnDraft(tx, locationId, userId, sessionId);
  const lines = await tx
    .select({ id: countLines.id, ingredientId: countLines.ingredientId })
    .from(countLines)
    .where(and(eq(countLines.sessionId, sessionId), eq(countLines.locationId, locationId)));
  if (lines.length === 0) throw new CountError("Count at least one ingredient before you submit.");

  const submittedAt = countTime;
  const stock = await stockAt(tx, locationId, submittedAt, lines.map((line) => line.ingredientId));
  for (const line of lines) {
    await tx
      .update(countLines)
      .set({ theoreticalQty: stockOf(stock, line.ingredientId), updatedAt: new Date() })
      .where(and(eq(countLines.id, line.id), eq(countLines.locationId, locationId)));
  }
  await tx
    .update(countSessions)
    .set({ status: "submitted", submittedAt })
    .where(and(eq(countSessions.id, sessionId), eq(countSessions.locationId, locationId)));
  return submittedAt;
}

export type ApprovalResult = { adjustments: number; openingLines: number };

/**
 * Approves a submitted count (owners and managers; RLS refuses anyone else).
 * As of the count time, per line: theoretical stock, today's cost as the
 * snapshot, the opening flag, and a count_adjust of counted - theoretical.
 *
 * An ingredient's first count (no earlier count adjustment of it, and no line
 * in an earlier approved count) is an opening count: its difference is the
 * starting balance, not unexplained usage (DECISIONS.md 13, 69, 72).
 */
export async function approveCount(tx: Tx, locationId: string, userId: string, sessionId: string): Promise<ApprovalResult> {
  // One approval or late correction at a time per restaurant (see migration 0011).
  await tx.execute(sql`select pg_advisory_xact_lock(hashtextextended(${`ledger:${locationId}`}, 0))`);

  const [session] = await tx
    .select({ status: countSessions.status, submittedAt: countSessions.submittedAt })
    .from(countSessions)
    .where(and(eq(countSessions.id, sessionId), eq(countSessions.locationId, locationId)))
    .for("update");
  if (!session) throw new CountError("This count no longer exists.");
  if (session.status !== "submitted" || !session.submittedAt) {
    throw new CountError(session.status === "draft" ? "This count has not been submitted yet." : "This count was already reviewed.");
  }
  const countTime = session.submittedAt;

  const lines = await tx
    .select({
      id: countLines.id,
      ingredientId: countLines.ingredientId,
      countedQty: countLines.countedQty,
      cost: ingredients.costPerBaseUnit,
    })
    .from(countLines)
    .innerJoin(ingredients, eq(ingredients.id, countLines.ingredientId))
    .where(and(eq(countLines.sessionId, sessionId), eq(countLines.locationId, locationId)));
  if (lines.length === 0) throw new CountError("This count has no lines.");
  const ingredientIds = lines.map((line) => line.ingredientId);

  const stock = await stockAt(tx, locationId, countTime, ingredientIds);
  const earlierCounts = await tx
    .selectDistinct({ ingredientId: stockMovements.ingredientId })
    .from(stockMovements)
    .where(
      and(
        eq(stockMovements.locationId, locationId),
        eq(stockMovements.type, "count_adjust"),
        inArray(stockMovements.ingredientId, ingredientIds),
        lte(stockMovements.occurredAt, countTime),
      ),
    );
  // A count that matched exactly wrote no adjustment, so earlier approved count lines count too.
  const earlierLines = await tx
    .selectDistinct({ ingredientId: countLines.ingredientId })
    .from(countLines)
    .innerJoin(countSessions, eq(countSessions.id, countLines.sessionId))
    .where(
      and(
        eq(countLines.locationId, locationId),
        inArray(countLines.ingredientId, ingredientIds),
        eq(countSessions.status, "approved"),
        lte(countSessions.submittedAt, countTime),
        sql`${countSessions.id} <> ${sessionId}`,
      ),
    );
  const counted = new Set([...earlierCounts, ...earlierLines].map((row) => row.ingredientId));

  const movements: NewMovement[] = [];
  let openingLines = 0;
  for (const line of lines) {
    const theoreticalQty = stockOf(stock, line.ingredientId);
    const isOpening = !counted.has(line.ingredientId);
    if (isOpening) openingLines += 1;
    await tx
      .update(countLines)
      .set({ theoreticalQty, unitCost: line.cost, isOpening, updatedAt: new Date() })
      .where(and(eq(countLines.id, line.id), eq(countLines.locationId, locationId)));
    const delta = toDecimal(line.countedQty).minus(toDecimal(theoreticalQty));
    if (!delta.isZero()) {
      movements.push({
        ingredientId: line.ingredientId,
        qtyDelta: toDbQty(delta),
        type: "count_adjust",
        refTable: "count_lines",
        refId: line.id,
        note: isOpening ? "Opening count" : null,
        occurredAt: countTime,
        createdBy: userId,
      });
    }
  }

  const approved = await tx
    .update(countSessions)
    .set({ status: "approved", approvedBy: userId, approvedAt: new Date() })
    .where(and(eq(countSessions.id, sessionId), eq(countSessions.locationId, locationId)))
    .returning({ id: countSessions.id });
  // RLS lets only owners and managers through; anyone else changes nothing.
  if (approved.length === 0) throw new CountError("You do not have permission to approve counts.");
  // Written after the status, so later counts see this one; its own adjustments are never "late" for it.
  await appendMovements(tx, locationId, movements);
  return { adjustments: movements.length, openingLines };
}

/** Rejects a submitted count. Nothing touches the ledger. */
export async function rejectCount(
  tx: Tx,
  locationId: string,
  userId: string,
  sessionId: string,
  note: string | null,
): Promise<void> {
  const [session] = await tx
    .select({ status: countSessions.status })
    .from(countSessions)
    .where(and(eq(countSessions.id, sessionId), eq(countSessions.locationId, locationId)))
    .for("update");
  if (!session) throw new CountError("This count no longer exists.");
  if (session.status !== "submitted") throw new CountError("Only a submitted count can be rejected.");
  const updated = await tx
    .update(countSessions)
    .set({ status: "rejected", approvedBy: userId, approvedAt: new Date(), reviewNote: note })
    .where(and(eq(countSessions.id, sessionId), eq(countSessions.locationId, locationId)))
    .returning({ id: countSessions.id });
  if (updated.length === 0) throw new CountError("You do not have permission to review counts.");
}

/** Throws away a draft (its own counter, or a manager). */
export async function deleteDraftCount(tx: Tx, locationId: string, sessionId: string): Promise<void> {
  const deleted = await tx
    .delete(countSessions)
    .where(and(eq(countSessions.id, sessionId), eq(countSessions.locationId, locationId), eq(countSessions.status, "draft")))
    .returning({ id: countSessions.id });
  if (deleted.length === 0) throw new CountError("This draft no longer exists.");
}
